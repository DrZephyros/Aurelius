import fs from "node:fs";
import path from "node:path";

/* The v8 Vite app bundled every source file as raw text via import.meta.glob("?raw").
   Next/Turbopack has no such thing, so this tiny generator does the same job ahead of time:
   it snapshots the real files into src/generated/raw-*.ts. It runs whenever next.config.ts loads
   (dev + build) and only rewrites a file when its content actually changed. */

const ROOT = process.cwd();

function walk(dir: string, out: string[] = []): string[] {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out.sort();
}

const rel = (p: string) => "/" + path.relative(ROOT, p).split(path.sep).join("/");

function collect(dir: string, test: (key: string) => boolean): Record<string, string> {
  const o: Record<string, string> = {};
  for (const f of walk(path.join(ROOT, dir))) {
    const k = rel(f);
    if (test(k)) o[k] = fs.readFileSync(f, "utf8");
  }
  return o;
}

function emit(name: string, data: Record<string, string>) {
  const file = path.join(ROOT, "src/generated", name);
  const body = `/* AUTO-GENERATED by scripts/gen-raw.ts — do not edit. */\nconst RAW: Record<string, string> = ${JSON.stringify(data)};\nexport default RAW;\n`;
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === body) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
}

export function generateRaw() {
  emit("raw-demos.ts", collect("demos-src", (k) => /\.(html|css|js)$/.test(k)));
  emit("raw-kit.ts", collect("kit-src", (k) => k.endsWith(".html")));
  emit(
    "raw-registry.ts",
    collect("src/registry", (k) => /\/[^/]+\/[^/]+\/(README\.md|[^/]+\.tsx)$/.test(k) && !k.endsWith("/demo.tsx")),
  );
  emit(
    "raw-bundles.ts",
    collect("src/bundles", (k) => /\.(ts|tsx|css)$/.test(k) && !k.endsWith("/BundlesIndex.tsx") && !k.endsWith("/download.ts")),
  );
  emitDemoLoaders();
  emit("raw-skill.ts", collect("skill-src", () => true));
}

// replaces the old Vite glob of every demo.tsx: explicit, code-split loaders for each component demo
function emitDemoLoaders() {
  const keys = walk(path.join(ROOT, "src/registry"))
    .map(rel)
    .filter((k) => k.endsWith("/demo.tsx"))
    .map((k) => k.replace("/src/registry/", "").replace("/demo.tsx", ""));
  const lines = keys.map((k) => `  ${JSON.stringify(k)}: () => import(${JSON.stringify("@/registry/" + k + "/demo")}),`);
  const body = `/* AUTO-GENERATED by scripts/gen-raw.ts — do not edit. */\nimport type { ComponentType } from "react";\nexport const DEMO_LOADERS: Record<string, () => Promise<{ default: ComponentType }>> = {\n${lines.join("\n")}\n};\n`;
  const file = path.join(ROOT, "src/generated/demo-loaders.ts");
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === body) return;
  fs.writeFileSync(file, body);
}
