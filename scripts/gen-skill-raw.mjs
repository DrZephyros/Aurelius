/* Re-embeds skill-src/aura-3d-web into the site bundle after the skill changes.
     node scripts/gen-skill-raw.mjs
   Writes:
     src/generated/raw-skill.ts          every text file of the skill (path → content), used by the paid download
     src/generated/raw-skill-public.ts   SKILL_INDEX (path, lines, bytes) of the whole skill + the free sample files

   (The original scripts/gen-raw.ts that produced these is not in the repo; this reproduces the same output shape
    for the skill portion only. The demos / kit / registry maps are untouched.) */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = "skill-src/aura-3d-web";
const TEXT = /\.(md|ts|tsx|css|html|json|mjs|js)$/i;
const SKIP = new Set(["node_modules", "dist", "shots", ".git"]);
const FREE = new Set([
  "examples/01-nocta-earbuds-product.md",
  "examples/README.md",
  "references/01-aura-doctrine.md",
  "references/09-prompt-pack.md",
  "templates/AURA_BRIEF.template.md",
  "templates/STORYBOARD.template.md",
]);

const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    if (SKIP.has(n)) return [];
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : TEXT.test(n) ? [p] : [];
  });

const files = walk(ROOT).map((p) => relative(ROOT, p).split("\\").join("/")).sort((a, b) => {
  // README + SKILL first, then examples / references / starter / templates (matches the previous ordering)
  const rank = (x) => (x === "README.md" ? 0 : x === "SKILL.md" ? 1 : x.startsWith("examples/") ? 2 : x.startsWith("references/") ? 3 : x.startsWith("starter/") ? 4 : 5);
  return rank(a) - rank(b) || a.localeCompare(b);
});

const read = (rel) => readFileSync(join(ROOT, rel), "utf8");
const HEAD = "/* AUTO-GENERATED by scripts/gen-skill-raw.mjs — do not edit. */\n";

const all = Object.fromEntries(files.map((f) => [`/skill-src/aura-3d-web/${f}`, read(f)]));
writeFileSync("src/generated/raw-skill.ts", `${HEAD}const RAW: Record<string, string> = ${JSON.stringify(all)};\nexport default RAW;\n`);

const index = files.map((f) => ({ path: f, lines: read(f).split("\n").length, bytes: Buffer.byteLength(read(f)) }));
const pub = Object.fromEntries(files.filter((f) => FREE.has(f)).map((f) => [`/skill-src/aura-3d-web/${f}`, read(f)]));
writeFileSync(
  "src/generated/raw-skill-public.ts",
  `${HEAD}export const SKILL_INDEX: { path: string; lines: number; bytes: number }[] = ${JSON.stringify(index)};\nconst RAW: Record<string, string> = ${JSON.stringify(pub)};\nexport default RAW;\n`,
);
console.log(`skill files: ${files.length} · free: ${Object.keys(pub).length} · ${(JSON.stringify(all).length / 1024).toFixed(0)} KB`);
