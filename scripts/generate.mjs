// Generates src/generated/*.json (template metrics + component registry index). Runs automatically from next.config.ts.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "src", "generated");
fs.mkdirSync(out, { recursive: true });
const write = (name, data) => {
  const file = path.join(out, name);
  const next = typeof data === "string" ? data : JSON.stringify(data, null, 1) + "\n";
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== next) fs.writeFileSync(file, next);
};

/* ── 3D template metrics ───────────────────────── */
const demos = path.join(root, "public", "demos");
const rd = (p) => fs.readFileSync(path.join(demos, p), "utf8");
const metrics = {};
for (const e of fs.readdirSync(demos, { withFileTypes: true })) {
  if (!e.isDirectory() || e.name.startsWith("_")) continue;
  const text = ["index.html", "style.css", "main.js"].map((f) => rd(`${e.name}/${f}`)).concat(rd("_shared/core.js"), rd("_shared/base.css")).join("\n");
  metrics[e.name] = { lines: text.split("\n").length, chars: text.length, tokens: Math.round(text.length / 4), kb: Math.round(Buffer.byteLength(text) / 1024) };
}
write("manifest.json", { metrics });

/* ── component registry ───────────────────────────
   src/registry/<category>/<slug>/{README.md, <slug>.tsx, demo.tsx}
   README.md starts with a --- frontmatter block (name, tagline, tags, deps). */
const reg = path.join(root, "src", "registry");
const CATS = JSON.parse(fs.readFileSync(path.join(reg, "categories.json"), "utf8"));
const parseFront = (md) => {
  const m = md.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = {};
  if (m) for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i < 0) continue;
    const k = line.slice(0, i).trim();
    const v = line.slice(i + 1).trim();
    meta[k] = v.startsWith("[") ? v.slice(1, -1).split(",").map((x) => x.trim()).filter(Boolean) : v;
  }
  return meta;
};
const items = [];
const demoLines = [];
for (const cat of CATS) {
  const dir = path.join(reg, cat.slug);
  if (!fs.existsSync(dir)) continue;
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!e.isDirectory()) continue;
    const base = path.join(dir, e.name);
    if (!fs.existsSync(path.join(base, "README.md"))) continue;
    const md = fs.readFileSync(path.join(base, "README.md"), "utf8");
    const meta = parseFront(md);
    const src = fs.readFileSync(path.join(base, `${e.name}.tsx`), "utf8");
    items.push({
      category: cat.slug,
      slug: e.name,
      name: meta.name || e.name,
      tagline: meta.tagline || "",
      tags: meta.tags || [],
      deps: meta.deps || [],
      file: `${e.name}.tsx`,
      lines: src.split("\n").length,
      order: Number(meta.order || 50),
    });
    demoLines.push(`  "${cat.slug}/${e.name}": dynamic(() => import("./${cat.slug}/${e.name}/demo"), { ssr: false }),`);
  }
}
items.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
write("registry.json", { categories: CATS, items });
write(
  path.join("..", "registry", "demos.ts"),
  `// GENERATED by scripts/generate.mjs — do not edit.\n"use client";\n\nimport dynamic from "next/dynamic";\nimport type { ComponentType } from "react";\n\nexport const DEMOS: Record<string, ComponentType> = {\n${demoLines.join("\n")}\n};\n`
);
console.log(`[generate] ${Object.keys(metrics).length} templates, ${items.length} registry items`);
