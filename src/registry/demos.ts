import { lazy, type ComponentType } from "react";
import { DEMO_LOADERS } from "@/generated/demo-loaders";

/* Every component folder ships a demo.tsx (site preview only). They are code-split and loaded on demand.
   The loader map is generated by scripts/gen-raw.ts (Next has no import.meta.glob). */
export const DEMOS: Record<string, ComponentType> = Object.fromEntries(
  Object.entries(DEMO_LOADERS).map(([k, load]) => [k, lazy(load)])
);
