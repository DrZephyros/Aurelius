import data from "@/generated/registry.json";

/* The modular component library lives in src/registry/<category>/<slug>/ — one folder per piece:
     <slug>.tsx   the drop-in component   ·   README.md   agent-ready install + usage instructions   ·   demo.tsx   site preview only
   registry.json is generated by scripts/generate.mjs from those folders. */

export type RegCategory = { slug: string; name: string; icon: string; blurb: string };
export type RegItem = { category: string; slug: string; name: string; tagline: string; tags: string[]; deps: string[]; file: string; lines: number; order: number };

export const REG_CATS = data.categories as RegCategory[];
export const REG_ITEMS = data.items as RegItem[];
export const TEXT_EFFECTS = "text-effects";

/** Text effects get their own top-level shelf. */
export const catHref = (c: string) => (c === TEXT_EFFECTS ? "/text-effects" : `/components/${c}`);
export const itemHref = (c: string, s: string) => `${catHref(c)}/${s}`;
export const itemsOf = (c: string) => REG_ITEMS.filter((i) => i.category === c);
export const catBySlug = (c: string) => REG_CATS.find((x) => x.slug === c);
export const getItem = (c: string, s: string) => REG_ITEMS.find((i) => i.category === c && i.slug === s);
export const downloadHref = (category?: string, slug?: string) => `/api/registry/download${category ? `?category=${category}${slug ? `&slug=${slug}` : ""}` : ""}`;
export const zipName = (category?: string, slug?: string) => (slug ? `${slug}.zip` : category ? `aurelius-${category}.zip` : "aurelius-components.zip");

/** The brief you paste into Claude Code / Cursor / Codex. */
export function agentPrompt(item: RegItem, readme: string): string {
  return `Add the Aurelius "${item.name}" component to this project.

1. Read the README below fully — it is the source of truth for install, props and gotchas.
2. Copy ${item.file} (I will attach / paste it) into this project's components folder (e.g. components/aurelius/${item.file}); match the project's import alias and code style.
3. Use it where I describe below. Configure it through props / CSS variables; do not rewrite the component.
4. Verify it type-checks and renders without hydration warnings.

Where to use it: [DESCRIBE THE PAGE / SECTION]

----- README.md -----
${readme.trim()}`;
}
